/// Each operator, over a premultiplied destination, with a straight source at full and partial
/// cover, pinned to C++ comp_op_adaptor_rgba<rgba8, order_bgra>::blend_pix (comp_op_rgba_minus
/// called directly, as it is not in C++'s table). The values were traced from the reference
/// renderer's patched agg_pixfmt_rgba.h (see the header).
#[test]
fn blend_matches_cpp_agg() {
    for (op, d, s, cover, e) in BLEND_CASES {
        let mut image = Image::new(1, 1, 4, 0);
        image.bytes.copy_from_slice(&d);
        let mut pf = PixfmtRgba32CompOp::new_with_op(&mut image.rows, op);

        pf.blend_pixel(
            0,
            0,
            &Rgba8::new(s[0] as u32, s[1] as u32, s[2] as u32, s[3] as u32),
            cover,
        );

        let expected = Rgba8::new(e[0] as u32, e[1] as u32, e[2] as u32, e[3] as u32);
        assert_eq!(
            pf.pixel(0, 0),
            expected,
            "{op:?} dst {d:?} src {s:?} cover {cover}"
        );
    }
}

/// A span goes through the blender's operator pixel by pixel, each at its own cover.
#[test]
fn blend_pixels_uses_the_operator_and_each_cover() {
    let mut image = Image::new(2, 1, 4, 255);
    let mut pf = PixfmtRgba32CompOp::new_with_op(&mut image.rows, CompOp::Difference);
    let colors = [Rgba8::new(0, 0, 255, 255), Rgba8::new(0, 0, 255, 255)];

    pf.blend_color_hspan(0, 0, 2, &colors, &[255, 0], 255);

    assert_eq!(pf.pixel(0, 0), Rgba8::new(255, 255, 0, 255));
    assert_eq!(pf.pixel(1, 0), Rgba8::new(255, 255, 255, 255));
}
